export function parseAs14Csv(): PinMapping[] {
  const lines = rawAs14Csv.split('\n');
  const result: PinMapping[] = [];
  
  let currentUport = '';
  let currentBoard = '';
  let currentCd = '';
  let currentLane = '';
  
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    
    const parts = line.split(',');
    while (parts.length < 8) {
      parts.push('');
    }
    
    const uport = parts[0].trim();
    const board = parts[1].trim();
    const cd = parts[2].trim();
    const lane = parts[3].trim();
    const connectorPinOld = parts[4].trim();
    const connector = parts[5].trim();
    const chipPinName = parts[6].trim();
    const chipPinCode = parts[7].trim();
    
    if (uport) currentUport = uport;
    if (board) currentBoard = board;
    if (cd) currentCd = cd;
    if (lane) currentLane = lane;
    
    result.push({
      uport: currentUport,
      board: currentBoard,
      cd: currentCd,
      lane: currentLane,
      connectorPinOld,
      connector,
      chipPinName,
      chipPinCode: chipPinCode || '-'
    });
  }
  
  return result;
}

export function queryAs14Pin(cdNo: string, laneNo: string, type: 'RX' | 'TX'): PinMapping[] {
  const data = parseAs14Csv();
  const normalizedCd = cdNo.trim().toLowerCase();
  // Strip any 'lane' prefix and extract number for standardizing lane matching
  const normalizedLane = laneNo.trim().toLowerCase().replace('lane', '');
  const typeStr = type.toUpperCase();
  
  return data.filter(row => {
    // Match CD
    const rowCd = row.cd.trim().toLowerCase();
    if (rowCd !== normalizedCd && rowCd.replace('cd', '') !== normalizedCd) {
      return false;
    }
    
    // Match LANE
    const rowLane = row.lane.trim().toLowerCase().replace('lane', '');
    if (rowLane !== normalizedLane) {
      return false;
    }
    
    // Match TYPE (RX / TX)
    // Check if connector (Col 5) has RX or TX
    if (row.connector && row.connector.toUpperCase().includes(typeStr)) {
      return true;
    }
    
    // Fallback detection using Col 4 (connectorPinOld) or Col 6 (chipPinName) if Col 5 is missing
    const fallbackText = (row.connectorPinOld || '' + row.chipPinName || '').toUpperCase();
    if (fallbackText) {
      if (typeStr === 'RX') {
        return fallbackText.includes('RX') || fallbackText.includes('RD') || fallbackText.includes('RDP') || fallbackText.includes('RDN');
      } else {
        return fallbackText.includes('TX') || fallbackText.includes('TD') || fallbackText.includes('TDP') || fallbackText.includes('TDN');
      }
    }
    
    return false;
  });
}
